"""Generate readable package views of the class diagram from diagrams/Class_Diagram.puml.

Usage:  python3 class_views.py <diagrams_dir>
Each view keeps the classes of one package with all members, shows the neighbour classes of other
packages as name-only boxes (so cross-package associations stay visible) and removes the rest.
Edit Class_Diagram.puml only; the view files are regenerated by the build.
"""
import sys
from pathlib import Path

VIEWS = {
    'Class_View_1_Accounts': {
        'title': 'Class Diagram - view 1: Accounts and access control',
        'full': ['$acc', 'AccountStatus', 'CustomerType'],
        'neighbours': ['Order', 'Cart', 'Review', 'Product', 'StockTransaction'],
    },
    'Class_View_2_Catalogue': {
        'title': 'Class Diagram - view 2: Catalogue and inventory',
        'full': ['$cat', 'StorageCondition'],
        'neighbours': ['Customer', 'StaffMember', 'CartItem', 'OrderItem'],
    },
    'Class_View_3_Sales': {
        'title': 'Class Diagram - view 3: Sales, payment and delivery',
        'full': ['$sales', 'OrderStatus', 'ShippingMethod', 'PaymentMethod', 'PaymentStatus', 'VoucherType'],
        'neighbours': ['Customer', 'Product', 'StoreBranch', 'Account'],
    },
}


def main(diagrams: Path):
    src = (diagrams / 'Class_Diagram.puml').read_text(encoding='utf-8')
    body = src.split('\n')
    for name, v in VIEWS.items():
        out = []
        for line in body:
            if line.startswith('@startuml'):
                line = f'@startuml {name}'
            elif line.startswith('title '):
                line = f"title {v['title']}"
            elif line.strip() == 'left to right direction':
                continue  # small views read better top-down
            elif line.strip() == '@enduml':
                out.append("' ---- view filter (generated by tools/class_views.py) ----")
                out.append('remove *')
                out += [f'restore {x}' for x in v['full'] + v['neighbours']]
                out += [f'hide {x} members' for x in v['neighbours']]
                out += [f'hide {x} circle' for x in v['neighbours']]
            out.append(line)
        (diagrams / f'{name}.puml').write_text('\n'.join(out), encoding='utf-8')
        print('wrote', diagrams / f'{name}.puml')


if __name__ == '__main__':
    main(Path(sys.argv[1] if len(sys.argv) > 1 else '.'))
